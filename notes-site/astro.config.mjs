// notes-site/astro.config.mjs — the private site, dist/notes at /notes.
//
// One package, two Starlight builds. The public build lives at
// astro.config.mjs and emits dist/docs; this one emits dist/notes and mounts
// at /notes, which is where nginx serves it behind the identity gate. The
// reason they are two builds and not one is the reason this repository is
// structured around visibility: private content never shares a directory,
// a dist tree, a search index or a sitemap with public content, so a
// mistake at any single layer cannot cross the boundary.
//
// WHAT IS DELIBERATELY DIFFERENT FROM THE PUBLIC SITE
//   - The sidebar is autogenerated. The public site's sidebar is a claim
//     maintained by hand because it encodes a reading order; the notes tree
//     is a working register that changes weekly, and a hand-maintained list
//     over two thousand lines of decisions is a list that rots.
//   - `pagefind: false` here too, and for a different reason: a search index
//     over private notes is an artifact that must be served behind the same
//     gate as the pages. Search is a deferred decision (see the README), not
//     an oversight — when it lands, the index is a third gated artifact.
//   - `editLink` is absent. The notes repository (anywaye/notes) is private;
//     an edit link to it on an authenticated page is a link to a repository
//     the reader may not be able to open, and this site does not pretend
//     otherwise.
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { computedSidebar } from '../sidebar.mjs';

export default defineConfig({
  site: 'https://docs.anywaye.com',
  base: '/notes',
  // The second build in one package: `--config notes-site/astro.config.mjs`
  // moves the config, not the project root, so without this the notes build
  // would read the PUBLIC tree's collections and pages. srcDir points both
  // here — the collection (content.config.ts) and the one page this site
  // owns (pages/404.astro) live under notes-site/src/, and bin/sync-content
  // materializes into notes-site/src/content/docs/.
  srcDir: 'notes-site/src',
  outDir: 'dist/notes',
  trailingSlash: 'ignore',
  integrations: [
    starlight({
      title: 'anywaye notes',
      description:
        'anywaye private notes — decisions, operations, debt and the notes that never belonged in a public repository.',
      social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/anywaye' }],
      credits: true,
      // Starlight injects /notes/404 by default, which collides with its own
      // catch-all over the docs collection. This site owns /404 itself in
      // notes-site/src/pages/404.astro; the injected route is turned off, the
      // same way the public site does it.
      disable404Route: true,
      pagefind: false,
      lastUpdated: false,
      // Computed from the tree at config time — see notes-site/sidebar.mjs
      // for why a hand-written list over a synced tree is a second, smaller
      // map of a territory this repository does not own. Top-level entries
      // are named there; the pages beneath each directory are autogenerated
      // by Starlight, so a page added to the notes repository appears in the
      // nav on its own.
      sidebar: computedSidebar('notes-site/src/content/docs', 'Notes'),
    }),
  ],
});
