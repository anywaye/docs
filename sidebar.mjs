import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/** 'source' when the last build was a tenant build, 'fleet' otherwise. */
export function lastBuildMode() {
  const marker = join(dirname(fileURLToPath(import.meta.url)), '.sync', 'mode');
  return existsSync(marker) && readFileSync(marker, 'utf8').trim() === 'source' ? 'source' : 'fleet';
}

function humanize(name) {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

/**
 * A sidebar computed from a content directory: the home page, one entry per
 * top-level page, one autogenerated group per top-level directory. Groups
 * wrap their autogenerate in an items array because Starlight removed
 * `label` directly on `autogenerate` in 0.39.0.
 */
export function computedSidebar(docsDir, homeLabel) {
  if (!existsSync(docsDir)) {
    return [{ label: homeLabel, items: [{ label: 'Home', link: '/' }] }];
  }
  const items = [{ label: 'Home', link: '/' }];
  for (const entry of readdirSync(docsDir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (entry.name.startsWith('_')) continue;
    if (entry.isDirectory()) {
      items.push({ label: humanize(entry.name), items: [{ autogenerate: { directory: entry.name } }] });
    } else if (/^[^/]+\.mdx?$/.test(entry.name) && entry.name !== 'index.md' && entry.name !== 'index.mdx') {
      items.push({ slug: entry.name.replace(/\.mdx?$/, '') });
    }
  }
  return [{ label: homeLabel, items }];
}
