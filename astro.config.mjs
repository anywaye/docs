// astro.config.mjs — the anywaye docs site.
//
// STATUS: scaffold. The site is static (Astro's default, no adapter) and the
// gate is `npm run build`, which runs Starlight's frontmatter validation and
// Astro's content collection checks. A page that does not validate fails the
// build rather than shipping a broken sidebar.
//
// WHAT IS DELIBERATELY ABSENT, and why — read before adding any of it:
//   - `pagefind: false` — the packet forbids search indexing, and Starlight's
//     default is to build a Pagefind index at the end of every build. Turn it
//     on only with a decision to maintain a search index.
//   - no sitemap, no analytics, no blog. A docs site that indexes itself into
//     third-party services is a privacy and maintenance surface we have not
//     agreed to carry.
//
// site: the canonical origin. Every internal link and the sitemap Astro would
// generate resolve against it, so it must be the real one at deploy time.
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { computedSidebar, lastBuildMode } from './sidebar.mjs';

// The fleet site's curated sidebar, verbatim. Wrapped in a function only so
// the config reads as one expression in both modes.
function CURATED_SIDEBAR() {
  return [
        { label: 'Home', link: '/' },
        // `Pricing, licence and security` answers the three questions a stranger
        // evaluating a purchase has and cannot answer from the rest of the site:
        // what it costs, what they are legally agreeing to, and what happens to
        // their credentials. It sits directly under `Hosted pilot` because the
        // same reader reaches both — somebody who has evaluated the platform and
        // is now looking for the commercial terms — and it sits there rather than
        // at the bottom so it is not buried under runbooks a buyer never opens.
        {
          label: 'Pricing, licence and security',
          items: [{ slug: 'commercial' }, { slug: 'security' }],
        },
        {
          label: 'Start here',
          items: [{ slug: 'getting-started' }],
        },
        {
          label: 'Upgrading',
          items: [{ slug: 'upgrading' }],
        },
        {
          label: 'Architecture',
          items: [
            { slug: 'architecture' },
            { slug: 'observability' },
            // `error-tracking` sits under Architecture because it is the third
            // leg of the same story: what the platform observes, where an
            // unhandled error goes, and how it gets there.
            { slug: 'error-tracking' },
          ],
        },
        {
          label: 'Services',
          items: [{ autogenerate: { directory: 'services' } }],
        },

        // `Projects` is synced, not authored here: bin/sync-content copies
        // each fleet repository's docs/ into src/content/docs/projects/<name>
        // before the build. A repository that documents its own API therefore
        // has no authoring surface in this repository at all — its pages
        // arrive from the repository that owns the code. A `notes/`
        // directory inside a public repository fails the sync (see
        // bin/sync-content), so private per-project pages never exist in this
        // tree by construction.
        //
        // The group sits directly under `Services` because the two answer
        // adjacent questions — what the service owns, and what its own manual
        // says — and nothing in the sidebar tells a reader which of the two
        // sites a page came from once it is mounted side by side.
        {
          label: 'Projects',
          items: [{ autogenerate: { directory: 'projects' } }],
        },
        // The error-contract tree: one generated page per envelope `code`
        // behind the frozen `docs.anywaye.com/errors/<code>` base (PLAN §1
        // stability rule 2). Autogenerated like `services`, so a new code's
        // page is reachable by construction, and collapsed because twenty-two
        // codes are a reference, not a narrative.
        {
          label: 'Errors',
          collapsed: true,
          items: [{ autogenerate: { directory: 'errors' } }],
        },
        {
          label: 'Runbooks',
          items: [
            { slug: 'runbooks' },
            // `deployment` sits first because it is the runbook an operator
            // reaches for before any other: it is how the stack gets installed
            // and how it changes afterwards. The rest are incident procedures.
            { slug: 'runbooks/deployment' },
            { slug: 'runbooks/backup-and-restore' },
            { slug: 'runbooks/secret-rotation' },
            { slug: 'runbooks/service-down' },
          ],
        },
        // The advisory feed sits after `Runbooks` and before `Troubleshooting`
        // because it answers a different question from either. A runbook is a
        // procedure you follow when your deployment is broken; troubleshooting
        // is the same ground keyed by symptom. An advisory is a condition you
        // have not hit yet, written for a reader who does not run anywaye at
        // all — so it belongs at the point where a stranger arrives, after the
        // material written for operators. `advisories` is autogenerated like
        // `services`: a new file in the directory appears in the sidebar
        // without a second edit, which is what keeps "every page is reachable
        // from the sidebar" true by construction rather than by memory.
        {
          label: 'Advisories',
          items: [{ autogenerate: { directory: 'advisories' } }],
        },
        { slug: 'troubleshooting' },
        { slug: 'guides' },
      ]
}

export default defineConfig({
  site: 'https://docs.anywaye.com',
  // Two builds, two trees: this site emits dist/docs, the private site emits
  // dist/notes (notes-site/astro.config.mjs). They are kept apart on disk on
  // purpose — one `cp -r dist` mistake must not be able to publish private
  // pages. nginx serves / from dist/docs and /notes/ from dist/notes, the
  // second behind the identity gate.
  outDir: 'dist/docs',
  trailingSlash: 'ignore',
  integrations: [
    starlight({
      title: 'anywaye',
      description:
        'anywaye — the open-source, multi-language SaaS platform. One CLI, independent services, connected by typed contracts.',
      // No `logo` yet: there is no brand asset in this repository, and an SVG
      // invented here would be a logo the project has not approved.
      social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/anywaye' }],
      editLink: {
        baseUrl: 'https://github.com/anywaye/docs/edit/master/src/content/docs/',
      },
      credits: true,
      // Starlight injects a /404 route by default, which collides with a
      // catch-all `/[...slug]` over the docs collection. We own /404 ourselves
      // in src/pages/404.astro, so the injected route is turned off rather than
      // left to win a route race and log a warning on every build.
      disable404Route: true,
      // Forbid search indexing (packet: "no search indexing"). See the header.
      pagefind: false,
      lastUpdated: false,
      // The sidebar is a claim about the site: every `slug:` here is resolved by
      // Starlight at build time (a dangling one fails the build) and re-checked
      // against dist/ by tests/smoke.mjs. Add the page and the entry in the same
      // commit, and never one without the other.
      //
      // Section order follows the three readers this site has: someone deciding
      // whether to adopt anywaye (Start here → Architecture → Services), someone
      // who already runs it and is moving to the current contracts (Upgrading),
      // then someone keeping it alive (Runbooks → Troubleshooting). `services`
      // is the hub the first two point back at.
      //
      // `Upgrading` sits before `Architecture` deliberately. It is the page a
      // self-hoster with a live deployment reaches for first, and burying it
      // under Runbooks — where a reader looks when something is already broken —
      // is how a rename lands as a silent gap in somebody's webhook handler.
      // Two sidebars, one build. A fleet build keeps the curated reading
      // order below, written for the readers this site has; a tenant build
      // (bin/sync-content --source) computes its navigation from the
      // tenant's own content, because the curated order promises slugs a
      // tenant never shipped and a red build over content nobody controls
      // is a gate nobody acts on. .sync/mode says which ran.
      sidebar: lastBuildMode() === 'source'
        ? computedSidebar('src/content/docs', 'docs')
        : CURATED_SIDEBAR()
    }),
  ],
});