#!/usr/bin/env node
// tests/smoke.mjs — the build-output suite, over BOTH build trees.
//
// WHY THIS FILE EXISTS
//   The docs repository has no runtime: it is Markdown plus a build. The only
//   thing that can break is the build, and the build is the gate
//   (`bin/prime` = `npm ci && npm run build && npm test`). So this suite's job
//   is to assert that builds actually produced sites, and specifically the
//   pages the navigation promises. A green `npm run build` with an empty
//   dist/ would otherwise pass silently.
//
// WHY IT NOW COVERS TWO TREES
//   The repository builds twice: the public site into dist/docs and the
//   private notes site into dist/notes (mounted at /notes). They are two
//   artifacts because private and public content never share a directory, so
//   a single misplaced copy cannot publish one to the other. A suite that
//   watched only the public tree would let the notes site rot silently —
//   which is the failure this repository cannot see otherwise, because the
//   notes tree is materialized by bin/sync-content and authored elsewhere.
//
//   The checks that differ per site are parameterized (see buildTargets);
//   the checks that are identical (index exists, no empty <svg>, internal
//   links resolve) loop over both.
import { strict as assert } from 'node:assert';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { test } from 'node:test';

const root = resolve(import.meta.dirname, '..');
const publicConfig = join(root, 'astro.config.mjs');
const notesConfig = join(root, 'notes-site', 'astro.config.mjs');

/**
 * The two builds the suite runs against.
 *
 * `base` is the mount point the build declares, and it decides how a link in
 * the built HTML is read: the notes build emits /notes-rooted URLs because
 * it is mounted there behind the identity gate. A /notes/favicon.svg in the
 * public build is unchanged behaviour — `/`-rooted hrefs are their own site's
 * links in both trees, and the favicon exception below is exactly the set of
 * static assets either tree references.
 */
const buildTargets = [
  {
    label: 'public',
    dir: join(root, 'dist', 'docs'),
    docs: join(root, 'src', 'content', 'docs'),
    base: '/',
    // The public site's sidebar is hand-maintained and is the claim the
    // per-site checks below are written against.
    config: publicConfig,
    sidebar: true,
    knownMissingAssets: ['/favicon.svg'],
  },
  {
    label: 'notes',
    dir: join(root, 'dist', 'notes'),
    docs: join(root, 'notes-site', 'src', 'content', 'docs'),
    base: '/notes',
    // The notes site's sidebar is autogenerated over its whole tree, so the
    // "every sidebar slug has a page" assertions are meaningless there — the
    // sidebar cannot promise a page that does not exist, and the reverse
    // check ("every page is reachable") is the only direction left. It runs
    // below with `sidebar: false`.
    config: notesConfig,
    sidebar: false,
    // The favicon gap is per-tree on purpose: the notes build base-prefixes
    // its asset hrefs (`/notes/favicon.svg`) because it is mounted there, so
    // the exception list for this tree names that spelling. Two entries for
    // the same missing brand asset, one per tree, and deleting them is the
    // same single decision in both.
    knownMissingAssets: ['/notes/favicon.svg'],
  },
];

/** Every HTML file under a directory. */
function htmlFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const entry of readdirSync(d, { withFileTypes: true })) {
      const full = join(d, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith('.html')) out.push(full);
    }
  };
  walk(dir);
  return out;
}

/**
 * Strip comments and string literals out of a JS source file, so a `slug:`
 * inside a comment cannot become a test assertion. Line comments and block
 * comments only — the config has no regex literals or template strings whose
 * contents matter here.
 */
function stripComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/** Every `slug: '…'` in a config's sidebar, plus the literals of any `{ link: '/' }`. */
function sidebarSlugs(configFile) {
  const source = stripComments(readFileSync(configFile, 'utf8'));
  const slugs = [...source.matchAll(/slug:\s*'([^']+)'/g)].map((m) => m[1]);
  const links = [...source.matchAll(/\blink:\s*'([^']*)'/g)].map((m) => m[1]);
  return { slugs, links };
}

/**
 * Every directory a config's sidebar autogenerates from.
 *
 * A directory entry covers its pages implicitly, so the reverse-coverage test
 * has to read it — otherwise every service page looks unreachable and the
 * assertion is unsatisfiable rather than true.
 */
function autogeneratedDirectories(configFile) {
  const source = stripComments(readFileSync(configFile, 'utf8'));
  return [...source.matchAll(/autogenerate:\s*\{\s*directory:\s*'([^']+)'/g)].map((m) => m[1]);
}

/** Every content page on disk, as canonical URL paths, excluding the home page. */
function contentPages(docs) {
  const pages = [];
  const walk = (dir, prefix = '') => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        walk(join(dir, entry.name), rel);
      } else if (/\.mdx?$/.test(entry.name)) {
        const stem = rel.replace(/\.mdx?$/, '');
        // Starlight's docsLoader drops a trailing `/index`, so
        // `runbooks/index.md` and `runbooks.md` are the same slug. The home
        // page (`index.mdx`) slugifies to the empty string, which is `/`.
        pages.push(canonicalPath(stem.replace(/\/index$/, '').replace(/^index$/, '')));
      }
    }
  };
  walk(docs);
  return pages.sort();
}

/** One leading slash, no trailing slash, `/` for the empty path. */
function canonicalPath(p) {
  const trimmed = p.replace(/^\/+/, '').replace(/\/+$/, '');
  return trimmed === '' ? '/' : `/${trimmed}`;
}

/**
 * The content file a Starlight slug maps to. Starlight's docsLoader sluggifies
 * the filename and drops the extension, so `services/identity.md` serves
 * `/services/identity/`. Directories get an `index` file.
 */
function sourceFileFor(slug, docs) {
  const base = slug.replace(/^\/+|\/+$/g, '');
  const asFile = base ? join(docs, `${base}.md`) : join(docs, 'index.mdx');
  const asDir = join(docs, base, 'index.md');
  return existsSync(asFile)
    ? asFile
    : existsSync(join(docs, `${base}.mdx`))
      ? join(docs, `${base}.mdx`)
      : asDir;
}

/** The built HTML path for a URL path, matching Astro's default `directory` format. */
function htmlFor(urlPath) {
  const clean = urlPath.replace(/^\/+/, '').replace(/\/+$/, '');
  return clean === '' ? 'index.html' : `${clean}/index.html`;
}

// --------------------------------------------------------------- both trees

for (const target of buildTargets) {
  test(`[${target.label}] dist/index.html exists, is non-empty, and is HTML`, () => {
    const index = join(target.dir, 'index.html');
    assert.ok(
      existsSync(index),
      `${target.dir}/index.html missing — run \`npm run build\` before \`npm test\` (looked in ${target.dir})`,
    );
    assert.ok(statSync(index).size > 0, `${target.label} index.html is empty`);
    assert.match(readFileSync(index, 'utf8'), /<html/i, `${target.label} index.html is not an HTML document`);
  });

  test(`[${target.label}] every content page is on disk and in dist/`, () => {
    // The reverse-coverage direction the public site's sidebar check needs is
    // in the public-only block below; what BOTH trees need is the plain fact
    // the notes site cannot afford to lose: every page the sync materialized
    // reached dist/. The notes tree is cleared and rebuilt by bin/sync-content,
    // so a regression in the sync shows up here as a page count mismatch.
    const expected = contentPages(target.docs);
    assert.ok(expected.length > 0, `no content pages under ${target.docs} — did the sync run?`);
    const missing = expected
      .map((page) => [page, canonicalPath(page)])
      .filter(([, route]) => !existsSync(join(target.dir, htmlFor(route))))
      .map(([page, route]) => `${page} (${route} -> ${htmlFor(route)})`);
    assert.deepEqual(
      missing,
      [],
      `[${target.label}] pages on disk with nothing in dist/: ${missing.join('; ')} — run \`npm run build\` first`,
    );
  });

  test(`[${target.label}] no built page contains an empty <svg>`, () => {
    // An icon name Starlight does not know renders as an empty <svg> — no
    // warning, no build failure, and a card that looks slightly wrong rather
    // than broken. That is worse than a red build, because nothing reports it.
    //
    // Found by writing one: `icon="seti:changelog"` is a valid *Seti UI* name
    // and Starlight 0.42 has no `seti:` prefix support at all, so the card
    // shipped an empty element for a whole release cycle. It is asserted here
    // because the only way to know an icon resolved is to look at the built
    // output, and nothing else in the pipeline looks. Scanned over the
    // rendered pages so it catches an empty icon anywhere — a Card, an Aside,
    // a component prop — rather than only the places an icon is written.
    const pages = htmlFiles(target.dir);
    assert.ok(pages.length > 0, `no HTML under ${target.dir} — run \`npm run build\` first`);

    // `<svg …/>` or `<svg …></svg>` with nothing between the tags. Attribute
    // values are matched loosely because the class hashes change per build.
    const empty = /<svg\b[^>]*\/>|<svg\b[^>]*>\s*<\/svg>/g;
    const offenders = pages
      .filter((page) => empty.test(readFileSync(page, 'utf8')))
      .map((page) => page.slice(target.dir.length + 1));
    assert.deepEqual(
      offenders,
      [],
      `[${target.label}] pages containing an empty <svg> (an icon name Starlight does not know, ` +
        `most likely — check the name against ` +
        '`node_modules/@astrojs/starlight/dist/components-internals/Icons.js`): ' +
        offenders.join(', '),
    );
  });

  test(`[${target.label}] every internal link in the built site resolves`, () => {
    // AGENTS.md names a broken link as one of the two ways this repository
    // breaks quietly: nothing validates an href, Starlight does not rewrite
    // or check them, and a page can point at a slug that was renamed two
    // commits ago and still build green. That is a 404 a reader finds, not a
    // red build a reviewer sees.
    //
    // Scanned over dist/ rather than over the Markdown, because that is what
    // a reader's browser resolves and it also catches links Starlight's
    // components emit rather than ones an author typed.
    const pages = htmlFiles(target.dir);
    assert.ok(pages.length > 0, `no HTML under ${target.dir} — run \`npm run build\` first`);

    const source = pages
      .map((page) => readFileSync(page, 'utf8'))
      .join('\n')
      // Code is not navigation. A page ABOUT link design — and the fleet has
      // one — quotes `<a href="/terms">` as its subject, in prose and in a
      // fence, and the quote renders into the HTML verbatim. Treating it as
      // a link makes the gate fail over markup that is documentation *of* an
      // anchor tag. So code spans are stripped before hrefs are collected:
      // Starlight renders every fenced block into a <pre> and every inline
      // span into a <code>, and neither is something a reader clicks.
      .replace(/<pre[^>]*>[\s\S]*?<\/pre>/g, '')
      .replace(/<code[^>]*>[\s\S]*?<\/code>/g, '');

    // Asset references are not links. `<link rel="icon">` and friends point at
    // a file the browser fetches on its own; nothing in the navigation depends
    // on them resolving, and treating them as links conflates two failures.
    //
    // One is nevertheless outstanding and this assertion says so out loud
    // rather than absorbing it: Starlight's favicon schema is
    // `z.string().default('/favicon.svg')` with no way to omit it, and this
    // repository has no brand asset to put there. Inventing a mark is a brand
    // decision this project has explicitly not made (see the `logo:` note in
    // astro.config.mjs), so the 404 stands, recorded, until that decision is.
    //
    // The exception is asserted to be EXACTLY this list rather than filtered
    // by a pattern, so a second asset 404 fails the suite instead of joining
    // a growing allowlist nobody reads.
    const knownMissingAssets = target.knownMissingAssets;
    const assetRefs = [
      ...source.matchAll(/<link\b[^>]*rel="[^"]*\bicon\b[^"]*"[^>]*>/g),
    ]
      .map((tag) => tag[0].match(/href="([^"]+)"/)?.[1])
      .filter((href) => href?.startsWith('/'));

    assert.deepEqual(
      [...new Set(assetRefs)].sort(),
      knownMissingAssets,
      'the set of referenced static assets changed. If the favicon now exists, ' +
        'delete it from knownMissingAssets in this file and from public/. If a new ' +
        'asset was added and is missing from dist/, ship it or remove the reference.',
    );

    // An href is internal when it is site-relative; the two trees are mounted
    // at / and /notes, so an href belongs to this tree when it is inside its
    // base (or is the root of this tree). An href rooted at the other tree's
    // base is a cross-tree link: the notes pages link back to the public site
    // by absolute URL (the links suite checks the shape), and the public site
    // never links /notes.
    const base = target.base.replace(/\/$/, '');
    const internal = [
      ...new Set(
        [...source.matchAll(/href="([^"]+)"/g)]
          .map((m) => m[1])
          .filter((h) => h.startsWith('/') && !h.startsWith('//'))
          .map((h) => h.split('#')[0])
          .filter((h) => h !== '' && !knownMissingAssets.includes(h)),
      ),
    ].filter((h) => (base === '' ? true : h === target.base || h.startsWith(`${base}/`)));

    // `trailingSlash: 'ignore'` means either spelling may be served, so accept
    // either — but not neither. A host that serves /x/ and not /x is its own
    // decision; a site that ships neither is broken.
    // A mounted page's hrefs carry the mount prefix (the notes tree emits
    // /notes/... because that is where nginx serves it), so the base is
    // stripped before the path is resolved against this tree's dist: the
    // base IS the dist directory. `/notes/decisions/` in the notes tree is
    // dist/notes/decisions/index.html.
    const resolves = (urlPath) => {
      let clean = urlPath.replace(/^\/+/, '').replace(/\/+$/, '');
      if (base !== '' && (clean === base.replace(/^\//, '') || clean.startsWith(`${base.replace(/^\//, '')}/`))) {
        clean = clean.replace(new RegExp(`^${base.replace(/^\//, '')}/?`), '');
      }
      if (clean === '') return existsSync(join(target.dir, 'index.html'));
      return (
        existsSync(join(target.dir, clean, 'index.html')) ||
        existsSync(join(target.dir, `${clean}.html`)) ||
        existsSync(join(target.dir, clean))
      );
    };

    const broken = internal.filter((href) => !resolves(href)).sort();

    assert.deepEqual(
      broken,
      [],
      `[${target.label}] internal links with nothing in dist/ behind them: ${broken.join(', ')} — a ` +
        'renamed or deleted page whose inbound links were not updated',
    );
  });
}

// ------------------------------------------------------------- public only

const publicTarget = buildTargets[0];

test('every sidebar slug has a page in src/content/docs/', () => {
  const { slugs } = sidebarSlugs(publicTarget.config);
  assert.ok(slugs.length > 0, 'no sidebar slugs found — did astro.config.mjs change shape?');

  const missing = slugs
    .map((slug) => [slug, sourceFileFor(slug, publicTarget.docs)])
    .filter(([, file]) => !existsSync(file))
    .map(([slug, file]) => `${slug} (looked for ${file})`);

  assert.deepEqual(missing, [], `sidebar slugs with no content file: ${missing.join('; ')}`);
});

test('every sidebar slug is in dist/ after a build', () => {
  const { slugs, links } = sidebarSlugs(publicTarget.config);
  const routes = [
    ...slugs.map((slug) => `/${slug}/`),
    // `link:` entries are absolute URLs or site-relative paths; an external
    // URL is not our page to build.
    ...links.filter((href) => href.startsWith('/')).map((href) => href),
  ];

  const missing = routes
    .map((route) => [route, htmlFor(route)])
    .filter(([, html]) => !existsSync(join(publicTarget.dir, html)))
    .map(([route, html]) => `${route} -> ${html}`);

  assert.deepEqual(
    missing,
    [],
    `sidebar routes missing from dist/docs/: ${missing.join(', ')} — run \`npm run build\` first`,
  );
});

test('the services directory is not empty', () => {
  const services = join(publicTarget.docs, 'services');
  assert.ok(existsSync(services), 'src/content/docs/services/ is missing');
  const pages = readdirSync(services).filter((f) => /\.mdx?$/.test(f));
  assert.ok(pages.length > 0, 'no service pages found in src/content/docs/services/');
});

test('every content page is reachable from the sidebar', () => {
  // The direction that was missing for a release: a page on disk and absent
  // from the navigation builds, lands in dist/, and passes every other check.
  //
  // Starlight's own behaviour is why: the docs collection picks up every file
  // under `src/content/docs/` whether or not the sidebar mentions it, so the
  // build is silent about a page that is only reachable by typing its URL.
  // The quiet failure this repository has the least defence against — a
  // reader who cannot find the migration note or the gates page concludes it
  // does not exist, and the page that was written carefully to correct a
  // wrong claim is the one nobody reads.
  const { slugs, links } = sidebarSlugs(publicTarget.config);
  const directories = autogeneratedDirectories(publicTarget.config);
  const covered = new Set([...slugs.map(canonicalPath), ...links.map(canonicalPath)]);

  const orphans = contentPages(publicTarget.docs).filter((page) => {
    if (covered.has(page)) return false;
    // An autogenerated group covers its own index page and everything beneath it.
    return !directories.some((dir) => {
      const d = canonicalPath(dir);
      return page === d || page.startsWith(`${d}/`);
    });
  });

  assert.deepEqual(
    orphans,
    [],
    `content pages with no sidebar entry: ${orphans.join(', ')} — add the page and ` +
      'the sidebar entry in the same commit (astro.config.mjs)',
  );
});
